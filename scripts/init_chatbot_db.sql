-- Synchrono AI Chatbot — PostgreSQL Conversation History Schema DDL
-- ==============================================================================
-- Target Database: synchrono_chatbot
-- Target Role: postgres / synchrono
-- Purpose: Persistent storage for conversational sessions, thread states, and message history
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. Conversation Sessions Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS conversations (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    title TEXT NOT NULL DEFAULT 'Percakapan Data Synchrono',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMENT ON TABLE conversations IS 'Stores user conversation sessions and auto-generated thread titles for Synchrono AI Chatbot';
COMMENT ON COLUMN conversations.id IS 'Unique conversation session identifier (UUIDv4)';
COMMENT ON COLUMN conversations.user_id IS 'Identifier of the authenticated user owning this conversation';
COMMENT ON COLUMN conversations.title IS 'Short human-readable summary title generated by LLM';
COMMENT ON COLUMN conversations.created_at IS 'Timestamp when the conversation was initiated';
COMMENT ON COLUMN conversations.updated_at IS 'Timestamp of the latest message activity in this conversation';

-- ------------------------------------------------------------------------------
-- 2. Chat Messages Table
-- ------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS messages (
    id VARCHAR(64) PRIMARY KEY,
    conversation_id VARCHAR(64) NOT NULL,
    role VARCHAR(16) NOT NULL CHECK (role IN ('human', 'ai', 'assistant', 'system')),
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_messages_conversation
        FOREIGN KEY (conversation_id)
        REFERENCES conversations(id)
        ON DELETE CASCADE
);

COMMENT ON TABLE messages IS 'Stores individual message bubbles (human prompts and AI responses) per conversation';
COMMENT ON COLUMN messages.id IS 'Unique message identifier (UUIDv4)';
COMMENT ON COLUMN messages.conversation_id IS 'Foreign key referencing the parent conversation session';
COMMENT ON COLUMN messages.role IS 'Message role author: human, ai, assistant, or system';
COMMENT ON COLUMN messages.content IS 'Full text or markdown content of the message';
COMMENT ON COLUMN messages.created_at IS 'Timestamp when the message was sent';

-- ------------------------------------------------------------------------------
-- 3. Performance & Query Optimization Indexes
-- ------------------------------------------------------------------------------
-- Accelerates listing conversations for a specific user ordered by latest activity
CREATE INDEX IF NOT EXISTS idx_conversations_user_updated 
    ON conversations(user_id, updated_at DESC);

-- Accelerates retrieving chronological message history for a conversation thread
CREATE INDEX IF NOT EXISTS idx_messages_conv_created 
    ON messages(conversation_id, created_at ASC);

-- ------------------------------------------------------------------------------
-- 4. Automated Timestamp Update Trigger
-- ------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION update_conversations_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trigger_conversations_updated_at ON conversations;

CREATE TRIGGER trigger_conversations_updated_at
BEFORE UPDATE ON conversations
FOR EACH ROW
EXECUTE FUNCTION update_conversations_updated_at();

